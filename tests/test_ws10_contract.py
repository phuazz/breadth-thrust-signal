def test_refuses_any_computation_before_the_burn_in_plus_its_own_window(sp):
    close, volume = ref.planted()
    burn = int(ws10.get(sp, "engine.constants.HL_LOOKBACK"))
    short = close.iloc[: burn + 15]                       # 267 sessions: 252 + 10 fits S-D2, 252 + 20 does not fit S-D3
    comp_short = cb.compute_composite(cb.build_panels(short, volume.iloc[: burn + 15]))
    assert comp_short["data_ok"].any()
    ws10.candidate_events(short, "S-D2", comp_short)
    with pytest.raises(ws10.BurnInRefusal):
        ws10.candidate_events(short, "S-D3", comp_short)
    tiny = close.iloc[:100]
    comp_tiny = cb.compute_composite(cb.build_panels(tiny, volume.iloc[:100]))
    assert not comp_tiny["data_ok"].any()
    for member in ("S-D3", "S-D2"):
        with pytest.raises(ws10.BurnInRefusal):
            ws10.candidate_events(tiny, member, comp_tiny)
        with pytest.raises(ws10.BurnInRefusal):
            ws10.fresh_events(ws10.candidate_share(tiny, member), 55.0, comp_tiny)


