def _extras(close, sp):
    extras = {}
    for member in ("S-D3", "S-D2"):
        fire = ws10.daily_fire(ws10.candidate_share(close, member), ws10.get(sp, f"candidates.{member}.threshold_pct"))
        fire.name = member
        extras[ws10.get(sp, f"candidates.{member}.dimension")] = fire
    return extras


