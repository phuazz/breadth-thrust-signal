def test_redundancy_rule_known_cases(sp):
    cal = pd.bdate_range("2020-01-02", periods=200)
    own = pd.DatetimeIndex([cal[50], cal[100], cal[150]])
    cand = pd.DatetimeIndex([cal[47], cal[53], cal[95], cal[106], cal[180]])    # leads 3, lags 3, leads 5, lags 6, far
    assert ws10.cofire_share(cand, own, cal) == 60.0, "a candidate that LEADS a member fire co-fires too"
    assert ws10.cofire_split(cand, own, cal) == {"before": 1, "same": 0, "after": 2}
    assert pd.isna(ws10.cofire_share(pd.DatetimeIndex([]), own, cal))
    none = pd.DatetimeIndex([])
    r = ws10.redundancy(cand, {"d1": none, "d2": none, "d3": own, "d4": none}, "d3", cal)
    assert r["own"] == 60.0 and r["d1"] == 0.0 and r["d4"] == 0.0 and r["status"] == "DISTINCT"
    assert r["n_events"] == 5 and r["thin"] is True
    heavy = pd.DatetimeIndex([cal[47], cal[53], cal[95], cal[106]])                 # 4 of 5 within the window
    r = ws10.redundancy(cand, {"d1": none, "d2": none, "d3": heavy, "d4": none}, "d3", cal)
    assert r["own"] == 80.0 and r["status"] == "REDUNDANT"
    r = ws10.redundancy(cand, {"d1": none, "d2": none, "d3": pd.DatetimeIndex([cal[47], cal[53], cal[95]]), "d4": own}, "d3", cal)
    assert r["own"] == 60.0 and r["d4"] == 60.0 and r["status"] == "DISTINCT", "equal shares are not MISPLACED"
    r = ws10.redundancy(cand, {"d1": none, "d2": none, "d3": pd.DatetimeIndex([cal[47]]), "d4": own}, "d3", cal)
    assert r["own"] == 20.0 and r["d4"] == 60.0 and r["status"] == "MISPLACED"
    ten = pd.DatetimeIndex([cal[i] for i in (50, 51, 52, 53, 54, 55, 56, 120, 150, 190)])
    exact70 = ws10.redundancy(ten, {"d1": none, "d2": none, "d3": pd.DatetimeIndex([cal[52]]), "d4": none}, "d3", cal)
    assert exact70["own"] == 70.0 and exact70["status"] == "DISTINCT", "exactly 70 is not above 70"
    assert exact70["n_events"] == 10 and exact70["thin"] is False
    assert ws10.redundancy(pd.DatetimeIndex([]), {"d1": none, "d2": none, "d3": own, "d4": none}, "d3", cal)["status"] == "NO_EVENTS"


