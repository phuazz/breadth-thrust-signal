def test_null_sets_reproduce_the_pinned_draws(fx, unit, sp):
    close, volume, panels, before, expected = fx
    ui, uv, ue = unit
    nu = expected["null_unit"]
    h = int(ws10.get(sp, "horizons.sessions.3m"))
    assert _dates(ue) == nu["events"]
    sets = ws10.null_sets(ue, uv, ui, h, 3, [19901228, 0])
    assert [_dates(s) for s in sets] == nu["first_three_draws_seed_0"], "the sequential sampler is pinned draw for draw"
    gap = int(ws10.get(sp, "clusters.gap_calendar_days"))
    pos = {d: i for i, d in enumerate(ui.index)}
    vset = set(uv)
    for s in ws10.null_sets(ue, uv, ui, h, 40, [19901228, 7]):
        assert len(s) == len(ue) and list(s) == sorted(s)
        assert all(d in vset for d in s)
        assert max(pos[d] for d in s) + 1 + h <= len(ui) - 1
        ids = ws10.cluster_ids(s, gap)
        assert len(set(ids)) == 12 and all(ids.count(k) == 2 for k in set(ids))
        for k in set(ids):
            pair = [d for d, i in zip(s, ids) if i == k]
            assert uv.get_loc(pair[1]) - uv.get_loc(pair[0]) == 7, "within-cluster offsets are preserved"
    again = ws10.null_sets(ue, uv, ui, h, 3, [19901228, 0])
    assert [_dates(s) for s in again] == nu["first_three_draws_seed_0"]
    other = ws10.null_sets(ue, uv, ui, h, 3, [19901228, 1])
    assert [_dates(s) for s in other] != nu["first_three_draws_seed_0"]


