def test_forward_stats_are_lagged_one_session(sp):
    cal = pd.bdate_range("2019-01-02", periods=60)
    spx = pd.Series(100.0 + np.arange(60), index=cal)
    k, h = 30, int(ws10.get(sp, "horizons.sessions.1m"))
    honest = spx.iloc[k + 1 + h] / spx.iloc[k + 1] - 1.0
    leaked = spx.iloc[k + h] / spx.iloc[k] - 1.0
    got = ws10.forward_stats(pd.DatetimeIndex([cal[k]]), spx, h)
    assert got["n"] == 1 and abs(got["median"] - honest) < 1e-12 and abs(got["median"] - leaked) > 1e-9
    assert ws10.forward_stats(pd.DatetimeIndex([cal[50]]), spx, h)["n"] == 0, "an incomplete window is dropped"


