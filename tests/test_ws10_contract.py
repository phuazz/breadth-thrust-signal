def test_step_then_flat_sits_above_its_ten_session_average_for_exactly_nine_sessions(sp):
    cal = pd.bdate_range("2021-01-04", periods=40)
    path = np.full(40, 100.0)
    path[20:] = 110.0                                  # one step on session 20, then exactly flat
    frame = pd.DataFrame({f"N{i:03d}": path for i in range(400)}, index=cal)
    share = ws10.candidate_share(frame, "S-D2")
    assert share.iloc[20:29].eq(100.0).all()           # sessions 20..28: above (j = 0..8)
    assert share.iloc[29] == 0.0                       # j = 9: the window is all 110, a tie is not "above"
    d3 = ws10.candidate_share(frame, "S-D3")
    assert d3.iloc[20:].eq(100.0).all()                # a step then flat stays at its 20-session high


