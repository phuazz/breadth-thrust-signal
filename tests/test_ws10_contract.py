"""Contract tests for the WS10 (thrust-subconditions) engine, committed at the freeze BEFORE the
engine exists. They define what ``scripts/ws10_subconditions.py`` and ``scripts/ws10_run.py`` must
do; the Opus build makes them pass without changing them. Every value comes from
``spec/ws10_prereg_spec.json`` (the engine reads it and never restates it) and from the planted
fixture ``tests/fixtures/ws10/expected.json`` regenerated by ``tests/make_ws10_fixture.py``, whose
reference implementation is the semantics of every function below where the words leave room.

Required API (frozen). scripts/ws10_subconditions.py:
  SPEC_PATH                                   Path of spec/ws10_prereg_spec.json
  load_spec() -> dict                         the spec
  get(spec, dotted) -> value                  raises FreezeViolation on a missing key (never a default)
  spec_hash() -> str                          sha256 hex of the spec file bytes
  FreezeViolation, BurnInRefusal, NonSessionDate, ComparatorMisuse   exception classes
  resolve_session(date, sessions) -> Timestamp               raises NonSessionDate if `date` is not in `sessions`
  candidate_share(close, member) -> Series                   per cent, 100 * count / members (multiplication first);
        a name counts only when its close and its rolling statistic are both defined (no forward fill, no padding);
        NaN where fewer than shared.share_nan_below_members members qualify; name == member
  daily_fire(share, threshold) -> Series[bool]               share >= threshold, NaN -> False
  fresh_events(share, threshold, comp) -> DatetimeIndex      first session at or above after shared.below_sessions
        consecutive DEFINED sessions strictly below; admitted on data_ok sessions at or after the first data_ok
        session; raises BurnInRefusal when comp has no data_ok session
  candidate_events(close, member, comp) -> DatetimeIndex     candidate_share then fresh_events; raises BurnInRefusal
        when len(close) < HL_LOOKBACK + the member's window_sessions (the burn-in plus its own 20 or 10)
  member_fresh_fires(boolean, comp) -> DatetimeIndex         existing_member_fresh_fire.rule on data_ok sessions
  cofire_share(cand_events, fire_dates, sessions) -> float   per cent of cand_events with a fire at most
        redundancy.window_sessions away in EITHER direction; NaN for an empty candidate set
  cofire_split(cand_events, fire_dates, sessions) -> {"before", "same", "after"}   counts of co-firing candidate
        events by whether the nearest fire is before, on, or after the candidate's session
  redundancy(cand_events, fires_by_dim, own_dimension, sessions) -> dict  keys own, d1, d4 (per cent), n_events,
        status in {DISTINCT, REDUNDANT, MISPLACED, NO_EVENTS} per redundancy.status_rule, thin (bool: n_events below
        redundancy.thin_suffix_below_events); fires_by_dim maps d1..d4 -> DatetimeIndex
  composite_with_members(panels, extra, config=None) -> DataFrame   compute_composite with extra {dim: Series[bool]}
        OR-ed into dim; equal to compute_composite(panels) on every engine column when every extra is False; an
        event is a session on which n_dimensions increases
  fresh_at(comp, threshold) -> DatetimeIndex                 event and n_dimensions >= threshold and data_ok
  before_set(comp, threshold) -> DatetimeIndex               the SEEN four-dimension set: takes no candidate argument
  added_events(before, after, threshold) -> DatetimeIndex    fresh_at(after) dates absent from fresh_at(before)
  removed_events(before, after, threshold) -> DatetimeIndex  fresh_at(before) dates absent from fresh_at(after)
  memory_window_share(added, before) -> float                per cent of `added` dates on which before.n_dimensions >= 1
  class CandidateRegistry: register(name, events); assert_comparator(events) raises ComparatorMisuse when `events`
        equals any registered candidate or added set
  forward_stats(events, index_series, horizon_sessions) -> {"n", "win_rate", "median"}  lagged one session (signal
        close T, window from the close of T+1); events whose lagged window is incomplete are dropped
  complete_window_events(events, index_series, horizon_sessions) -> DatetimeIndex   events at return-series position
        i with i + 1 + h at most the last index (horizons.complete_window_rule)
  forward_window_end(sessions, start, horizon_sessions) -> Timestamp    sessions[get_loc(start) + h]; NonSessionDate
  cluster_ids(dates, gap_days) -> list[int]; cluster_count(dates, gap_days) -> int   a gap > gap_days splits
  null_sets(events, valid_sessions, index_series, horizon_sessions, draws, seed_key) -> list[DatetimeIndex]
        the pinned SEQUENTIAL sampler (null.placement, null.restart) on the complete-window treatment events, with
        clusters.gap_calendar_days; one rng.integers(len(admissible)) call per cluster placement on
        numpy.random.default_rng(seed_key); identical to the reference ref_null_sets draw for draw
  null_draws(events, valid_sessions, index_series, horizon_sessions, draws, seed_key) -> ndarray (draws, 2)
        columns win_rate, median of each drawn set's lagged forward returns
  mc_p(observed, draw_values) -> float                       (1 + count at or beyond) / (1 + draws)
  per_horizon_p(p_win, p_med) -> float                       max
  holm(pvals, alpha) -> {"reject": {name: bool}, "steps": [{"name", "p", "threshold", "reject"}]}
  power(events, valid_sessions, index_series, horizon_sessions, delta_pp, null_values, draws, seed_key, alpha,
        family_size) -> float   share of sets drawn by the pinned sampler on seed_key whose max(p_win, p_med), after
        +delta_pp / 100 is added to every lagged return, is <= alpha / family_size against null_values
  self_drill(events, valid_sessions, index_series, horizon_sessions, null_values, drill_draws, seed_key) -> dict
        keys unconditional_win_rate, unconditional_median, null_mean_win_rate, null_mean_median, centring_pass,
        size_share_at_alpha, per self_drill in the spec (bands and alpha read from the spec)
  cell_status(cleared, power_keyed) -> "PASS" | "FAIL" | "UNRESOLVED"        power.cell_status_rule
  clause_status(early, late) -> "PASS" | "FAIL" | "UNRESOLVED"              power.clause_status_rule
  verdict(g1, g2, g3, stopped=False, thin=False) -> str     verdict.rule_in_order; g1 {cand: status}, g2 {cand: status}
scripts/ws10_run.py:
  Stop                                                      the FAIL_STOP exception
  spec_hash_or_stop(frozen) -> str                          Stop when the spec hash differs from `frozen`
  check_engine_modules(spec) -> dict                        Stop when any pinned module hash differs
  check_frozen_tree_clean(status_lines) -> None             Stop when PREREG_thrust-subconditions.md, spec/, tests/ or
        scripts/ws10_*.py appear modified, added, renamed or untracked in `git status --porcelain` lines
  event_set_guard(observed, expected) -> None               Stop when any key of `expected` differs in `observed`

Python months are 1-indexed. Date arithmetic goes through pandas only.
"""

